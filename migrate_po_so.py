class OdooConnection:
    """Thin wrapper around Odoo's XML-RPC API (works against any Odoo
    version - 16 and 19 both expose the same /xmlrpc/2/* endpoints)."""

    def __init__(self, url, db, username, password, label):
        self.url = url
        self.db = db
        self.label = label
        common = xmlrpc.client.ServerProxy(f"{url}/xmlrpc/2/common")
        self.uid = common.authenticate(db, username, password, {})
        if not self.uid:
            raise RuntimeError(
                f"[{label}] Authentication failed for user {username!r} "
                f"on db {db!r} at {url}"
            )
        self.password = password
        self.models = xmlrpc.client.ServerProxy(f"{url}/xmlrpc/2/object")

    def execute(self, model, method, *args, **kwargs):
        return self.models.execute_kw(
            self.db, self.uid, self.password, model, method, list(args), kwargs
        )

    def search_read(self, model, domain, fields, **kwargs):
        return self.execute(model, "search_read", domain, fields, **kwargs)

    def search(self, model, domain, **kwargs):
        return self.execute(model, "search", domain, **kwargs)

    def get_field_names(self, model):
        """Cached set of real field names on this connection for a given
        model. Used to drop fields that don't exist on this specific Odoo
        version instead of failing outright - field names occasionally
        differ between versions (e.g. purchase.order's notes/note field),
        and this makes the script resilient to that without needing to
        hardcode every possible variant."""
        if not hasattr(self, "_field_cache"):
            self._field_cache = {}
        if model not in self._field_cache:
            fields = self.execute(model, "fields_get", [], {"attributes": []})
            self._field_cache[model] = set(fields.keys())
        return self._field_cache[model]

    def create(self, model, vals):
        known = self.get_field_names(model)
        safe_vals = {}
        dropped = []
        for key, value in vals.items():
            if key not in known:
                dropped.append(key)
                continue
            # Also filter fields inside one2many command tuples like
            # order_line: [(0, 0, {...}), ...] - check each line's inner
            # dict against the actual line model's field list too, since
            # field names can differ there independently of the header
            # (e.g. product_uom vs product_uom_id, taxes_id vs tax_ids).
            if key == "order_line" and isinstance(value, list):
                line_model = ("purchase.order.line" if model == "purchase.order"
                              else "sale.order.line")
                line_known = self.get_field_names(line_model)
                new_lines = []
                for cmd in value:
                    if isinstance(cmd, (list, tuple)) and len(cmd) == 3 and cmd[0] == 0:
                        line_vals = cmd[2]
                        safe_line_vals = {}
                        for lkey, lvalue in line_vals.items():
                            if lkey in line_known:
                                safe_line_vals[lkey] = lvalue
                            else:
                                dropped.append(f"order_line.{lkey}")
                        new_lines.append((0, 0, safe_line_vals))
                    else:
                        new_lines.append(cmd)
                safe_vals[key] = new_lines
            else:
                safe_vals[key] = value
        if dropped:
            print(f"    [WARN] {model}: dropping field(s) not present on "
                  f"target - {', '.join(dropped)}")
        return self.execute(model, "create", safe_vals)


