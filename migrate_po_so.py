# Main
# ============================================================================

def main():
    # When output is piped (e.g. through `tee`), Python fully buffers
    # stdout instead of flushing per-line like it does on a live
    # terminal - meaning any print() still sitting in the buffer at the
    # moment of an unhandled crash can be lost entirely, never reaching
    # the terminal OR the piped file. Force line-buffering so nothing
    # gets silently dropped right before an error.
    sys.stdout.reconfigure(line_buffering=True)

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--apply", action="store_true",
        help="Actually create records in the target (v19) database. "
             "Without this flag, the script only prints what it would do."
    )
    parser.add_argument(
        "--only", metavar="NAME", default=None,
        help="Only process a single record by exact name (e.g. --only P01202). "
             "Useful for testing one record end-to-end before running the "
             "full batch. Matches against either PO or SO names."
    )
    args = parser.parse_args()

    print(f"Mode: {'APPLY (will write to target)' if args.apply else 'DRY-RUN (no changes will be made)'}")

    try:
        source = OdooConnection(**SOURCE, label="source/v16")
        target = OdooConnection(**TARGET, label="target/v19")
    except RuntimeError as e:
        print(f"ERROR: {e}")
        sys.exit(1)

    matcher = RecordMatcher(target)

    po_names = PO_NAMES
    so_names = SO_NAMES
    if args.only:
        po_names = [n for n in PO_NAMES if n == args.only]
        so_names = [n for n in SO_NAMES if n == args.only]
        if not po_names and not so_names:
            print(f"ERROR: --only {args.only!r} does not match any name in "
                  f"PO_NAMES or SO_NAMES.")
            sys.exit(1)

    migrate_purchase_orders(source, target, matcher, po_names, args.apply)
    migrate_sale_orders(source, target, matcher, so_names, args.apply)

    print("\n" + "=" * 70)
    print("SUMMARY")
    print("=" * 70)
    if matcher.unmatched:
        print("Unmatched records requiring manual attention in the target DB:")
        for kind, values in matcher.unmatched.items():
            print(f"  {kind}:")
            for v in sorted(values):
                print(f"    - {v}")
        print(
            "\nCreate/fix these in Odoo 19 first (matching by name/code/VAT "
            "with the source), then re-run this script - it skips orders "
            "that already exist, so it's safe to run again."
        )
    else:
        print("No unmatched partners/products/UoMs/taxes.")

    if not args.apply:
        print("\nThis was a DRY RUN. Re-run with --apply to actually create records.")


if __name__ == "__main__":
    main()