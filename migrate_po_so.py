class RecordMatcher:
    """Resolves a v16 record (partner, product, uom, tax) to its v19
    equivalent by business key, caching lookups. Anything it can't match
    is recorded in .unmatched for the final report - never silently
    guesses."""

    def __init__(self, target: OdooConnection):
        self.target = target
        self.partner_cache = {}
        self.product_cache = {}
        self.uom_cache = {}
        self.tax_cache = {}
        self.currency_cache = {}
        self.unmatched = defaultdict(set)

    def match_partner(self, src_partner):
        """src_partner: dict with at least 'id' and 'name'; ideally also
        'email' and 'vat' from a search_read on res.partner."""
        key = src_partner["id"]
        if key in self.partner_cache:
            return self.partner_cache[key]

        target_id = None
        vat = (src_partner.get("vat") or "").strip()
        email = (src_partner.get("email") or "").strip()
        name = (src_partner.get("name") or "").strip()

        if vat:
            found = self.target.search("res.partner", [["vat", "=", vat]], limit=1)
            if found:
                target_id = found[0]
        if not target_id and email:
            found = self.target.search("res.partner", [["email", "=", email]], limit=1)
            if found:
                target_id = found[0]
        if not target_id and name:
            found = self.target.search("res.partner", [["name", "=", name]], limit=1)
            if found:
                target_id = found[0]

        if target_id:
            # Found - leave the existing target partner exactly as-is.
            # Never overwrite it, even if source data has since changed -
            # whatever is already in v19 is treated as authoritative.
            self.partner_cache[key] = target_id
            return target_id

        # Not found - create it in the target instead of failing the
        # whole order over a missing vendor/customer.
        partner_vals = {
            "name": name,
            "email": email or False,
            "vat": vat or False,
            "phone": src_partner.get("phone") or False,
            "mobile": src_partner.get("mobile") or False,
            "street": src_partner.get("street") or False,
            "city": src_partner.get("city") or False,
        }
        partner_vals = {k: v for k, v in partner_vals.items() if v}
        target_id = self.target.create("res.partner", partner_vals)
        print(f"    [CREATE] partner {name!r} created in target as id={target_id}")

        self.partner_cache[key] = target_id
        return target_id

    def match_product(self, src_product):
        """src_product: dict with 'id', 'default_code', 'name'."""
        key = src_product["id"]
        if key in self.product_cache:
            return self.product_cache[key]

        target_id = None
        code = (src_product.get("default_code") or "").strip()
        name = (src_product.get("name") or "").strip()

        if code:
            found = self.target.search(
                "product.product", [["default_code", "=", code]], limit=1
            )
            if found:
                target_id = found[0]
        if not target_id and name:
            found = self.target.search(
                "product.product", [["name", "=", name]], limit=1
            )
            if found:
                target_id = found[0]

        if target_id:
            # Found - leave the existing target product exactly as-is,
            # same policy as vendors/customers: never overwrite it.
            self.product_cache[key] = target_id
            return target_id

        # Not found - create it in the target instead of failing the
        # order over a missing product. Kept intentionally minimal
        # (name + default_code only) since we don't have enough source
        # data here to safely set accounting/costing fields - those
        # should be reviewed and filled in manually in v19 afterward.
        product_vals = {"name": name}
        if code:
            product_vals["default_code"] = code
        target_id = self.target.create("product.product", product_vals)
        print(f"    [CREATE] product {name!r} created in target as id={target_id}")

        self.product_cache[key] = target_id
        return target_id

    def match_uom(self, src_uom_name):
        if src_uom_name in self.uom_cache:
            return self.uom_cache[src_uom_name]
        found = self.target.search("uom.uom", [["name", "=", src_uom_name]], limit=1)
        target_id = found[0] if found else None
        self.uom_cache[src_uom_name] = target_id
        if not target_id:
            self.unmatched["uom"].add(src_uom_name)
        return target_id

    def match_tax(self, src_tax_name, type_tax_use):
        cache_key = (src_tax_name, type_tax_use)
        if cache_key in self.tax_cache:
            return self.tax_cache[cache_key]
        found = self.target.search(
            "account.tax",
            [["name", "=", src_tax_name], ["type_tax_use", "=", type_tax_use]],
            limit=1,
        )
        target_id = found[0] if found else None
        self.tax_cache[cache_key] = target_id
        if not target_id:
            self.unmatched["tax"].add(f"{src_tax_name} ({type_tax_use})")
        return target_id

    def match_currency(self, src_currency_name):
        """Currencies are matched by their 3-letter ISO code (e.g. 'SAR',
        'USD', 'EUR', 'AED') - this code is stable and identical across
        any two Odoo databases, so no fuzzy matching is needed here."""
        if src_currency_name in self.currency_cache:
            return self.currency_cache[src_currency_name]
        found = self.target.search(
            "res.currency", [["name", "=", src_currency_name]], limit=1
        )
        target_id = found[0] if found else None
        self.currency_cache[src_currency_name] = target_id
        if not target_id:
            self.unmatched["currency"].add(src_currency_name)
        return target_id


def _copy_attachments(source, target, res_model, source_res_id, target_res_id, label):
    """Copy every file attachment from a source record to its newly
    created target record. Attachments aren't referenced by business key
    the way partners/products are - they're just files - so we copy them
    by name + raw content directly."""
    attachments = source.search_read(
        "ir.attachment",
        [["res_model", "=", res_model], ["res_id", "=", source_res_id]],
        ["name", "datas", "mimetype"],
    )
    for att in attachments:
        if not att.get("datas"):
            continue  # empty/placeholder attachment, nothing to copy
        target.create("ir.attachment", {
            "name": att["name"],
            "datas": att["datas"],
            "mimetype": att.get("mimetype") or False,
            "res_model": res_model,
            "res_id": target_res_id,
        })
    if attachments:
        print(f"    -> copied {len(attachments)} attachment(s) for {label}")


