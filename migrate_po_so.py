def migrate_purchase_orders(source, target, matcher, names, apply_changes):
    print("\n" + "=" * 70)
    print("PURCHASE ORDERS")
    print("=" * 70)

    orders = source.search_read(
        "purchase.order",
        [["name", "in", names]],
        [
            "name", "partner_id", "date_order", "date_planned", "partner_ref",
            "notes", "order_line", "currency_id",
        ],
    )
    found_names = {o["name"] for o in orders}
    for missing in set(names) - found_names:
        print(f"  [SKIP] {missing}: not found in source (Odoo 16)")

    for order in orders:
        name = order["name"]

        existing = target.search("purchase.order", [["name", "=", name]], limit=1)
        if existing:
            print(f"  [SKIP] {name}: already exists in target (id={existing[0]})")
            continue

        partner = source.search_read(
            "res.partner", [["id", "=", order["partner_id"][0]]],
            ["name", "email", "vat", "phone", "mobile", "street", "city"],
        )[0]
        target_partner_id = matcher.match_partner(partner)
        if not target_partner_id:
            print(f"  [FAIL] {name}: vendor {partner['name']!r} not found in target - skipped")
            continue

        target_currency_id = None
        if order.get("currency_id"):
            currency = source.search_read(
                "res.currency", [["id", "=", order["currency_id"][0]]], ["name"]
            )[0]
            target_currency_id = matcher.match_currency(currency["name"])
            if not target_currency_id:
                print(f"  [FAIL] {name}: currency {currency['name']!r} not found in target - skipped")
                continue

        lines = source.search_read(
            "purchase.order.line",
            [["id", "in", order["order_line"]]],
            ["product_id", "name", "product_qty", "price_unit",
             "product_uom", "taxes_id", "display_type"],
        )

        line_vals = []
        line_error = False
        for line in lines:
            if line.get("display_type") in ("line_section", "line_note"):
                # Real section header or free-text note from source -
                # preserve its actual type instead of collapsing both
                # into "note". Neither needs a product or quantity at all.
                line_vals.append((0, 0, {
                    "name": line["name"],
                    "display_type": line["display_type"],
                }))
                continue

            if not line["product_id"]:
                # No display_type set, but also no product - treat as a
                # plain note as a fallback (source data oddity).
                line_vals.append((0, 0, {
                    "name": line["name"],
                    "display_type": "line_note",
                }))
                continue

            if not line.get("product_qty"):
                # Some source lines have no quantity set at all (not even
                # 0.0 - a genuine missing value) - v19 rejects these
                # outright. Skip just this one line rather than crashing
                # the whole order, and flag it clearly for manual review.
                print(f"  [WARN] {name}: line {line['name']!r} has no "
                      f"quantity in source - line skipped, order still created")
                continue

            product = source.search_read(
                "product.product", [["id", "=", line["product_id"][0]]],
                ["default_code", "name"],
            )[0]
            target_product_id = matcher.match_product(product)
            if not target_product_id:
                print(f"  [FAIL] {name}: product {product['name']!r} not found in target")
                line_error = True
                continue

            uom = source.search_read(
                "uom.uom", [["id", "=", line["product_uom"][0]]], ["name"]
            )[0]
            target_uom_id = matcher.match_uom(uom["name"])

            # Source (v16) field is 'taxes_id' - correct, unrelated to target.
            target_tax_ids = []
            if line["taxes_id"]:
                taxes = source.search_read(
                    "account.tax", [["id", "in", line["taxes_id"]]],
                    ["name", "type_tax_use"],
                )
                for tax in taxes:
                    t_id = matcher.match_tax(tax["name"], tax["type_tax_use"])
                    if t_id:
                        target_tax_ids.append(t_id)

            # Target (v19) field is 'tax_ids' on purchase.order.line, not
            # 'taxes_id' - confirmed against the live server's fields_get.
            line_vals.append((0, 0, {
                "name": line["name"],
                "product_id": target_product_id,
                "product_qty": line["product_qty"],
                "price_unit": line["price_unit"],
                "product_uom_id": target_uom_id or False,
                "tax_ids": [(6, 0, target_tax_ids)],
            }))

        if line_error:
            print(f"  [FAIL] {name}: skipped due to unmatched product(s) above")
            continue

        vals = {
            "partner_id": target_partner_id,
            "partner_ref": order.get("partner_ref") or "",
            "date_order": order["date_order"],
            "date_planned": order.get("date_planned") or False,
            "note": order.get("notes") or "",
        }
        if target_currency_id:
            vals["currency_id"] = target_currency_id

        if not apply_changes:
            print(f"  [DRY-RUN] Would create PO {name} "
                  f"(vendor={partner['name']}, {len(line_vals)} line(s))")
            continue

        # Create the header first (no lines yet), then add lines one at a
        # time. If Odoo rejects a specific line (e.g. a data quirk that
        # slipped past our own checks), only that single line is skipped
        # - the order itself, and every other valid line, still goes
        # through instead of the whole order being lost.
        new_id = target.create("purchase.order", vals)
        target.execute("purchase.order", "write", [new_id], {"name": name})

        added, skipped = 0, 0
        for lv in line_vals:
            try:
                target.execute("purchase.order", "write", [new_id], {"order_line": [lv]})
                added += 1
            except xmlrpc.client.Fault as e:
                skipped += 1
                reason = e.faultString.splitlines()[-1] if e.faultString else str(e)
                print(f"  [WARN] {name}: line skipped - {reason}")
                print(f"    Line data: {lv}")

        _copy_attachments(source, target, "purchase.order", order["id"], new_id, name)
        status = f"{added} line(s) added" + (f", {skipped} skipped" if skipped else "")
        print(f"  [OK] {name}: created in target as id={new_id} ({status})")



