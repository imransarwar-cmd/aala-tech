#!/usr/bin/env python3
"""
Migrate specific Purchase Orders and Sale Orders from an Odoo 16 database
to an Odoo 19 database, using Odoo's XML-RPC API on both ends (no direct
DB access needed, works across versions).

WHY XML-RPC AND NOT RAW SQL / A DB DUMP:
Purchase/sale orders reference partners, products, taxes, UoMs, and
users - all of which have DIFFERENT internal IDs in the two databases.
Copying rows directly would silently point at the wrong partner/product
in v19. This script instead re-creates each order through Odoo's own API,
resolving each reference by a stable business key (partner: email/VAT/name,
product: default_code/name) so it lands on the correct v19 record, or is
clearly reported as unmatched if it can't be resolved automatically.

WHAT GETS MIGRATED PER ORDER:
    Partner/vendor, currency, order date, expected arrival (POs) /
    reference (SOs), notes, every order line (product, qty, price, UoM,
    taxes - each resolved to its v19 equivalent), and every file
    attachment on the record (quotes, scanned documents, etc. - copied
    by content, not by reference, since attachment IDs also differ
    between the two databases).

WHAT THIS DOES NOT DO:
- Delivery Notes (WH/OUT/..., WH/RET/...) are not recreated directly.
  They're generated by Odoo automatically as a side effect of confirming
  a Sale Order or receiving a Purchase Order - trying to fabricate them
  standalone would produce pickings disconnected from real stock moves.
  Once the SOs/POs below are migrated and confirmed/received in v19 in
  the same way they were in v16, the matching delivery notes will be
  created by Odoo itself.
- It does not delete or modify anything in Odoo 16 (source only, read-only).
- It skips (does not duplicate) any order that already exists in v19 by
  the same name - safe to re-run.

USAGE:
    1. Fill in the CONFIG section below (or set the environment variables
       it reads from).
    2. Test a single record first, dry-run (no changes made):
           python3 migrate_po_so.py --only P01202
    3. Once that output looks correct, apply it for real - still just
       the one record:
           python3 migrate_po_so.py --only P01202 --apply
    4. Check the result in Odoo 19's UI, then run the full batch:
           python3 migrate_po_so.py              # dry-run, all records
           python3 migrate_po_so.py --apply       # actually create them

REQUIREMENTS:
    Python 3 standard library only (xmlrpc.client) - nothing to pip install.
"""

